    private static final Map<String, Material> BY_NAME;

    static {
        Map<String, Material> byName = new HashMap<>();
        for (Material material : values()) byName.put(material.name(), material);
        BY_NAME = Collections.unmodifiableMap(byName);
    }

    private final boolean block;
    private final boolean item;
    private final boolean air;
    private final NamespacedKey key;

    Material(boolean block, boolean item, boolean air) {
        this.block = block;
        this.item = item;
        this.air = air;
        this.key = NamespacedKey.minecraft(name().toLowerCase(Locale.ROOT));
    }

    public boolean isBlock() { return block; }
    public boolean isItem() { return item; }
    public boolean isAir() { return air; }
    @Override public NamespacedKey getKey() { return key; }

    public static Material getMaterial(String name) {
        return BY_NAME.get(name);
    }

    public static Material matchMaterial(String name) {
        if (name == null) throw new IllegalArgumentException("Name cannot be null");
        String filtered = name;
        String vanillaPrefix = NamespacedKey.MINECRAFT + ":";
        if (filtered.startsWith(vanillaPrefix)) filtered = filtered.substring(vanillaPrefix.length());
        filtered = filtered.toUpperCase(Locale.ENGLISH);
        filtered = filtered.replaceAll("\\s+", "_").replaceAll("\\W", "");
        return getMaterial(filtered);
    }
